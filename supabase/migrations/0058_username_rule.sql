--
-- ★★★ ของเดิมคือ ^[a-z0-9._]{3,20}$ ซึ่งแคบกว่าความจริง
--
--     ★ ทดสอบกับ GoTrue ของโปรเจกต์นี้โดยตรงแล้ว:
--         "my-name"  → รับได้   (แต่ CHECK เดิมห้าม)
--         "Frame"    → รับได้ แล้วชนกับ "frame" ที่มีอยู่ (GoTrue ทำเป็นตัวเล็กเอง)
--         "สมชาย"    → ปฏิเสธ "Unable to validate email address: invalid format"
--     ★★ แปลว่าขีดกลางกับตัวพิมพ์ใหญ่ถูกห้ามโดยไม่มีเหตุผลทางเทคนิค
--        ส่วนภาษาไทยถูกห้ามโดยตัวระบบล็อกอินเอง ไม่ใช่โดย CHECK ตัวนี้
--
-- ★★ ยังเก็บเป็นตัวเล็กเสมอ — ฝั่งแอปทำ toLowerCase ก่อนบันทึก
--    ★ CHECK จึงรับ A-Z ไว้เป็นกันชน ไม่ใช่เพื่อให้เก็บตัวใหญ่ได้จริง
--      ★★ ถ้าวันหนึ่งมีทางเขียนที่ลืมแปลง ข้อมูลจะยังเข้าได้และไม่พัง
--         แต่ unique index ยังกันชื่อซ้ำได้เพราะทุกทางเขียนแปลงเหมือนกัน
--
-- ★ ไม่มี begin;/commit; — ตัวรันยิงทีละคำสั่งนอกทรานแซกชัน (เหตุผลใน 0056)

alter table public.profiles
  drop constraint if exists profiles_username_format;

alter table public.profiles
  add constraint profiles_username_format
  check (username is null or username ~ '^[A-Za-z0-9._-]{3,20}$');

comment on constraint profiles_username_format on public.profiles is
  'ชื่อผู้ใช้ 3–20 ตัว · a-z A-Z 0-9 . _ - · ไม่รับอักษรที่ไม่ใช่ ASCII เพราะถูกแปลงเป็นอีเมลปลอมให้ GoTrue (0058)';
