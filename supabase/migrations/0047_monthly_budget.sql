-- ★★ null = ยังไม่ได้ตั้ง ซึ่งต่างจาก 0 (ตั้งงบไว้ศูนย์บาท)
--    ★ หน้าเว็บแสดงคนละอย่างสองกรณีนี้: ลิงก์ "ตั้งงบรายเดือน" กับแถบที่เต็มทันที

alter table public.profiles
  add column if not exists monthly_budget numeric(12,2)
    constraint profiles_budget_nonneg
    check (monthly_budget is null or monthly_budget >= 0);

comment on column public.profiles.monthly_budget is
