-- ===========================================================================
-- 0046 · เบอร์พร้อมเพย์ — เพื่อสร้าง QR ที่มียอดเงินอยู่แล้ว
-- ===========================================================================
--
-- ★★★ ต่างจาก payment_qr_path ที่มีอยู่แล้ว และต้องมีทั้งคู่
--
--     ★ payment_qr_path คือ "รูป QR ที่ผู้ใช้อัปขึ้นมา" ★★ ซึ่งเป็นรูปนิ่ง
--       ★ QR พร้อมเพย์ที่ปรินต์หรือแคปมาจากแอปธนาคาร ไม่มียอดเงินอยู่ข้างใน
--         ★★ คนจ่ายต้องพิมพ์ยอดเองทุกครั้ง ซึ่งเป็นจุดที่พิมพ์ผิดได้
--            และเป็นเหตุผลที่คนโอนผิดจำนวนกันบ่อยที่สุด
--
--     ★ เก็บ "เบอร์/เลขบัตร" แล้วสร้าง QR เองตอนแสดง ทำให้ใส่ยอดลงไปได้
--       ★★ คนจ่ายสแกนแล้วยอดขึ้นมาเลย กดยืนยันอย่างเดียว
--
-- ★★ ไม่ลบ payment_qr_path — คนที่อัปรูปไว้แล้วต้องใช้งานได้ต่อ
--    ★ และบางคนใช้บัญชีที่ผูกพร้อมเพย์ไม่ได้ จึงต้องมีทางรูปภาพเสมอ

alter table public.profiles
  add column if not exists promptpay_id text
    constraint profiles_promptpay_len
    /*
     * ★ ตรวจแค่ความยาวกับชนิดตัวอักษรที่นี่ ไม่ตรวจว่าเป็นเบอร์จริงไหม
     *   ★★ เบอร์มือถือไทย 10 หลัก · เลขบัตรประชาชน 13 หลัก · เลขนิติบุคคล 13
     *      ★ ความถูกต้องจริงรู้ได้ตอนสแกนเท่านั้น — ด่านที่นี่กันแค่ขยะ
     */
    check (promptpay_id is null or promptpay_id ~ '^[0-9]{10,13}$');

comment on column public.profiles.promptpay_id is
  'เบอร์พร้อมเพย์หรือเลขบัตรประชาชน — ใช้สร้าง QR พร้อมยอดเงิน (0046)';
