/** ★ ช่วงอักษรไทยในยูนิโคด — ชุดเดียวกับที่ scripts/i18n-test.ts ใช้ */
const THAI = /[฀-๿]/

export function markThai(locale: string, text: string): React.ReactNode {
  if (locale === 'th' || !THAI.test(text)) return text
  return <span lang="th">{text}</span>
}
