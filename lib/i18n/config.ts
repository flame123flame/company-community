/**
 * ★★★ ของที่ผู้ใช้พิมพ์ไม่ได้อยู่ในภาษาของหน้า — ต้องติด dir="auto"
 *
 *     dir บน <html> ตัดสินทิศของ "ข้อความที่เราแปล" ★ แต่ชื่อห้อง ชื่อเพลง
 *       จาก YouTube ข้อความแชท และชื่อคน เป็นภาษาอะไรก็ได้ ไม่เกี่ยวกับ
 *       ภาษาที่คนอ่านเลือกไว้
 *
 *     ★★ คนไทยตั้งชื่อห้องเป็นอาหรับได้ และคนอาหรับเปิดเพลงไทยได้
 *        ข้อความอาหรับในหน้าไทยที่ไม่ติด dir="auto" จะสลับที่เครื่องหมาย
 *        วรรคตอน — "?كيف حالك" กลายเป็น "كيف حالك?" ซึ่งผิดในภาษานั้น
 *
 *     dir="auto" ให้เบราว์เซอร์เดาจากตัวอักษรที่มีน้ำหนักตัวแรกของก้อนนั้น
 *     ★ จึงถูกทั้งสองทางโดยไม่ต้องรู้ว่าข้อความนั้นเป็นภาษาอะไรมาก่อน
 *
 *     ★★ ห่อเฉพาะก้อนที่เป็นของผู้ใช้ ไม่เหวี่ยงไปทั้งย่อหน้า
 *        บรรทัดที่มีทั้งชื่อคนและคำแปล (เช่น "สมชาย (คุณ)") ต้องห่อแค่ชื่อ
 *        ★ ไม่งั้นคำแปลจะถูกลากไปตามทิศที่ชื่อคนเดาได้ ซึ่งไม่ใช่ทิศของมัน
 *
 *     ★ ด่าน scripts/i18n-test.ts ตรวจให้: มันมองว่าอะไรที่อยู่ใน dir="auto"
 *       คือของผู้ใช้ (ข้ามไป) ★★ อะไรที่เป็นตัวหนังสือไทยนอกนั้นบนหน้าภาษาอื่น
 *         คือของที่ลืมเรียก t() — ซึ่งเป็นความผิดที่หาด้วยตาไม่เจอ
 */
export const RTL_LOCALES = new Set<Locale>(['ar'])

export function isRtl(locale: Locale): boolean {
  return RTL_LOCALES.has(locale)
}

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value)
}

/**
 * เดาภาษาจาก Accept-Language
 *
 * ★ ใช้เฉพาะตอนยังไม่เคยเลือก — พอเลือกแล้ว cookie ชนะเสมอ
 *   คนที่ตั้งใจเลือกไทยทั้งที่เครื่องเป็นอังกฤษ ต้องได้ไทยทุกครั้ง
 */
export function pickFromHeader(header: string | null): Locale {
  if (!header) return DEFAULT_LOCALE
  for (const part of header.split(',')) {
    const tag = part.split(';')[0]?.trim().toLowerCase() ?? ''
    const base = tag.split('-')[0]
    if (isLocale(base)) return base
    // zh-TW / zh-CN ทั้งคู่ถือเป็นจีน
    if (base === 'zh') return 'zh'
  }
  return DEFAULT_LOCALE
}
