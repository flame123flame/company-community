/** สั้นสุดกี่ตัว — ตามที่เจ้าของระบบสั่ง */
export const USERNAME_MIN = 3
/** ยาวสุดกี่ตัว */
export const USERNAME_MAX = 20

/**
 * ★ รับตัวพิมพ์ใหญ่ด้วย แล้วค่อยแปลงเป็นตัวเล็กตอนบันทึก
 *   ★★ GoTrue แปลงอีเมลเป็นตัวเล็กเองอยู่แล้ว — "Frame" ชนกับ "frame"
 *      ที่มีอยู่จริง (ทดสอบแล้วได้ "already been registered")
 *      ★ การห้ามพิมพ์ใหญ่จึงไม่ได้กันอะไร นอกจากกันคนที่เผลอกด Shift
 */
export const USERNAME_RE = new RegExp(`^[A-Za-z0-9._-]{${USERNAME_MIN},${USERNAME_MAX}}$`)

/** ชื่อที่จะเก็บจริง — ตัดช่องว่างและทำเป็นตัวเล็ก */
export function normalizeUsername(raw: string): string {
  return raw.trim().toLowerCase()
}

export function isValidUsername(raw: string): boolean {
  return USERNAME_RE.test(raw.trim())
}
