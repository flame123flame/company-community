/**
 * ตัวเลือก "อื่น ๆ" — เป็นสัญลักษณ์ ไม่ใช่ค่าที่เก็บ
 *
 * ★★★ เดิมเทียบด้วย `department === 'อื่น ๆ'` ซึ่งเป็นข้อความที่ต้องแปล
 *
 *     ★ วันที่หน้านี้เป็นภาษาอังกฤษ ค่าใน <select> จะเป็น "Other"
 *       แล้วเงื่อนไขที่เทียบกับคำไทยจะเป็นเท็จตลอด
 *       ★★ ผลคือช่องพิมพ์ฝ่ายเองไม่โผล่ขึ้นมาเลย และคนที่อยู่ฝ่ายใหม่
 *          จะกรอกฝ่ายตัวเองไม่ได้ — โดยที่ฟอร์มดูปกติทุกอย่าง
 *
 *     ★ ใช้ค่าที่ไม่มีภาษา จึงไม่มีทางเพี้ยนตามคำแปล และไม่มีทางถูกเก็บ
 *       ลงฐานข้อมูลโดยบังเอิญเพราะมันถูกแทนด้วยสิ่งที่คนพิมพ์เสมอ
 */
export const DEPT_OTHER = '__other__'

/**
 * ค่าที่จะเก็บจริง — แปลง DEPT_OTHER เป็นสิ่งที่คนพิมพ์
 *
 * ★ รวมไว้ที่เดียวเพราะทั้งฟอร์มสมัครและหน้าโปรไฟล์ต้องตัดสินใจเหมือนกัน
 */
export function resolveDepartment(picked: string, typed: string): string {
  return picked === DEPT_OTHER ? typed.trim() : picked
}

/**
 * ป้ายของฝ่ายที่เก็บไว้ในฐานข้อมูล
 *
 * ★★★ ค่าในฐานข้อมูลเป็นไทย แต่คนอ่านอาจไม่ได้อ่านไทย
 *
 *     ★ ทุกที่ที่โชว์ `person.department` ตรง ๆ จะพ่นคำไทยออกมากลาง
 *       หน้าภาษาอื่น ★★ ซึ่งหาด้วยตาไม่เจอเพราะหน้าที่เหลือแปลถูกหมด
 *       และคนที่เจอก็ไม่รู้ว่ามันคืออะไร
 *
 * ★★ ฝ่ายที่ไม่อยู่ในรายการ (คนที่สมัครด้วย "อื่น ๆ" แล้วพิมพ์เอง) คืนค่าเดิม
 *    ★ มันเป็นข้อความที่ผู้ใช้พิมพ์ จึงไม่มีคำแปลให้และไม่ควรมี
 *      ★★ จุดที่แสดงผลลัพธ์นี้ควรห่อ dir="auto" เหมือนชื่อคน เพราะอาจเป็น
 *         ภาษาอะไรก็ได้ — ไม่เกี่ยวกับภาษาของหน้า
 */
export function departmentLabel(ot: Ot, value: string | null | undefined): string | null {
  if (!value) return null
  const found = DEPARTMENTS.find((d) => d.value === value)
  return found ? ot(found.labelKey) : value
}
