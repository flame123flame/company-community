import type { Ot } from '@/lib/i18n/office-format'

/**
 * บริษัทเจ้าของระบบ — ค่าที่เก็บลงฐานข้อมูล
 *
 * ★★★ เคยเก็บ ot('reg.companyName') ลงไปตรง ๆ ซึ่งคือ "คำแปล" ไม่ใช่ "ค่า"
 *
 *     ★ คนที่สมัครตอนหน้าเป็นภาษาไทยบันทึกชื่อไทย คนที่สมัครตอนเป็น
 *       ภาษาอังกฤษบันทึก "AWA Company Limited" ★★ บริษัทเดียวจึงกลายเป็น
 *       หลายค่าในคอลัมน์เดียว ตามภาษาที่คนนั้นเปิดหน้าไว้ตอนกดสมัคร
 *       ★ วัดได้จริงในฐานข้อมูลตอนเจอ: ไทย 4 แถว · อังกฤษ 6 แถว
 *
 *     ★★ ผลคือรายงานและตัวกรองของ Admin ที่จัดกลุ่มตามบริษัท จะนับ
 *        พนักงานบริษัทเดียวกันเป็นสองบริษัท — โดยไม่มีอะไรฟ้องเลย
 *
 * ★★ ใช้ชื่อไทยเป็นค่าตั้งต้น เพราะเป็นชื่อจดทะเบียนและเป็นค่าที่ข้อมูลจริง
 *    เก็บอยู่แล้ว ★ การเปลี่ยนไปเก็บรหัสสั้น ๆ จะทำให้แถวเก่ากับแถวใหม่
 *    เป็นคนละชุดโดยไม่มี migration
 *
 * ★ เหตุผลเดียวกับฝ่าย/แผนก — เขียนไว้ยาวกว่าใน departments.ts
 */
export const COMPANY_VALUE = 'บริษัท เอดับเบิ้ลยูเอ จำกัด (AWA Company Limited)'

/**
 * ป้ายของบริษัทที่เก็บไว้ในฐานข้อมูล
 *
 * ★ ค่าที่ตรงกับบริษัทเจ้าของระบบ แปลตามภาษาของคนอ่าน
 *   ★★ ค่าอื่น (ข้อมูลเก่าหรือที่ Admin กรอกเอง) คืนตามเดิม — เป็นข้อความ
 *      ที่คนพิมพ์ จึงไม่มีคำแปลให้ และจุดที่แสดงควรห่อ dir="auto"
 */
export function companyLabel(ot: Ot, value: string | null | undefined): string | null {
  if (!value) return null
  return value === COMPANY_VALUE ? ot('reg.companyName') : value
}
