/** ค่าที่ไปอยู่บน <html data-reveal="..."> */
export type RevealMode = 'css' | 'js'

/**
 * รันก่อนวาดเฟรมแรก — ตัดสินว่าเบราว์เซอร์นี้ใช้ทางไหน
 *
 * ★ เช็ก animation-timeline ตรง ๆ ไม่ใช่เดาจากชื่อเบราว์เซอร์
 *   วันที่ Safari รองรับขึ้นมา โค้ดนี้จะเปลี่ยนไปใช้ทางที่เร็วกว่าเองทันที
 *   โดยไม่มีใครต้องกลับมาแก้
 */
export const REVEAL_BOOT_SCRIPT = `(function(){try{
var css=window.CSS&&CSS.supports&&CSS.supports('animation-timeline','view()');
document.documentElement.dataset.reveal=css?'css':'js';
}catch(e){document.documentElement.dataset.reveal='off';}})();`
